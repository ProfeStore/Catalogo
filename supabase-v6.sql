-- El Profe Store · SQL v6 (marcas con logo)
-- Ejecutar DESPUÉS de supabase-v5.sql. Pégalo completo en Supabase → SQL Editor → Run. Es re-ejecutable.

-- 1) Marcas: nombre + logo (el logo se sube desde el admin a la carpeta images/ de GitHub)
create table if not exists public.marcas (
  id         bigint generated by default as identity primary key,
  name       text not null,
  image_url  text,                 -- ruta, ej: images/brand-1729300000-ab12cd.webp
  sort       integer not null default 0,
  created_at timestamptz not null default now()
);
alter table public.marcas enable row level security;
drop policy if exists "marcas todo" on public.marcas;
create policy "marcas todo" on public.marcas for all to anon, authenticated using (true) with check (true);

-- 2) Cada producto puede pertenecer a una marca
alter table public.productos add column if not exists brand_id bigint;
