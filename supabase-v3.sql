-- El Profe Store · SQL v3 (tallas hasta 42, galería de fotos por color, comentarios con moderación, ajustes)
-- Ejecutar DESPUÉS de supabase.sql y supabase-v2.sql. Pégalo completo en Supabase → SQL Editor → Run. Es re-ejecutable.

-- 1) Tallas: solo hasta la 42
alter table public.productos alter column sizes set default array[35,36,37,38,39,40,41,42];
update public.productos
   set sizes = coalesce((select array_agg(s order by s) from unnest(sizes) s where s <= 42), '{}');

-- 2) Galería de fotos por producto: [{"path":"images/xxx.webp","color_id":3}, ...]  (la primera es la principal)
alter table public.productos add column if not exists images jsonb not null default '[]'::jsonb;

-- 3) Comentarios de clientes (llegan como 'pending'; el admin los publica, oculta o elimina)
create table if not exists public.comentarios (
  id         bigint generated by default as identity primary key,
  name       text     not null check (char_length(name)  between 1 and 40),
  rating     smallint not null check (rating between 1 and 5),
  text       text     not null check (char_length(text)  between 1 and 400),
  image_url  text,
  status     text     not null default 'pending' check (status in ('pending','published','hidden')),
  created_at timestamptz not null default now()
);
alter table public.comentarios enable row level security;
drop policy if exists "comentarios leer"      on public.comentarios;
drop policy if exists "comentarios enviar"    on public.comentarios;
drop policy if exists "comentarios moderar"   on public.comentarios;
drop policy if exists "comentarios eliminar"  on public.comentarios;
create policy "comentarios leer"     on public.comentarios for select to anon, authenticated using (true);
create policy "comentarios enviar"   on public.comentarios for insert to anon, authenticated with check (status = 'pending');
create policy "comentarios moderar"  on public.comentarios for update to anon, authenticated using (true) with check (true);
create policy "comentarios eliminar" on public.comentarios for delete to anon, authenticated using (true);

-- 4) Fotos de los comentarios (bucket público, máx. 400 KB, solo imágenes)
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('comentarios', 'comentarios', true, 400000, array['image/webp','image/jpeg','image/png'])
on conflict (id) do update set file_size_limit = excluded.file_size_limit, allowed_mime_types = excluded.allowed_mime_types;
drop policy if exists "comentarios subir fotos"  on storage.objects;
drop policy if exists "comentarios borrar fotos" on storage.objects;
create policy "comentarios subir fotos"  on storage.objects for insert to anon, authenticated with check (bucket_id = 'comentarios');
create policy "comentarios borrar fotos" on storage.objects for delete to anon, authenticated using (bucket_id = 'comentarios');

