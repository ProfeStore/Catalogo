-- 1) Categorías registradas por el admin (el catálogo solo muestra las que existen aquí)
create table if not exists public.categorias (
  id         bigint generated by default as identity primary key,
  slug       text not null unique,          -- identificador interno, ej: 'deportivos' (es lo que guarda productos.cat)
  name       text not null,                 -- nombre visible, ej: 'Deportivos'
  sort       integer not null default 0,
  created_at timestamptz not null default now()
);
alter table public.categorias enable row level security;
drop policy if exists "categorias todo" on public.categorias;
create policy "categorias todo" on public.categorias for all to anon, authenticated using (true) with check (true);

-- Las 5 categorías que ya usaban tus productos (mismos identificadores)
insert into public.categorias (slug, name, sort)
select * from (values
  ('sport','Deportivos',1),('formal','Formales',2),('casual','Casuales',3),('boots','Botas',4),('sandals','Sandalias',5)
) v(slug,name,sort)
where not exists (select 1 from public.categorias);

-- 2) Los productos ya no están limitados a esas 5 categorías
alter table public.productos drop constraint if exists productos_cat_check;

-- 3) Video por producto (ruta en GitHub, ej: videos/1729300000-ab12cd.mp4, o un enlace directo a un .mp4)
alter table public.productos add column if not exists video_url text;

